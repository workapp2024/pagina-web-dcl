const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {PGlite}=require('@electric-sql/pglite');
test('proposed notices reserve only amounts, preserve idempotence and ownership, and never post money',async()=>{
 const db=new PGlite();
 const c='11111111-1111-4111-8111-111111111111',other='22222222-2222-4222-8222-222222222222',o='33333333-3333-4333-8333-333333333333',r='44444444-4444-4444-8444-444444444444',n='55555555-5555-4555-8555-555555555555',i='66666666-6666-4666-8666-666666666666';
 try {
 await db.exec(`CREATE ROLE anon;CREATE ROLE authenticated;CREATE ROLE service_role;
 CREATE TABLE customers(id uuid PRIMARY KEY,wholesale_enabled boolean DEFAULT true,wholesale_access_active boolean DEFAULT true,archived_at timestamptz);
 CREATE TABLE wholesale_orders(id uuid PRIMARY KEY,customer_id uuid,status text,confirmed_revision_id uuid);
 CREATE TABLE wholesale_order_revisions(id uuid PRIMARY KEY,order_id uuid,total_amount numeric,currency char(3),UNIQUE(order_id,id));
 CREATE TABLE wholesale_payment_entries(id uuid PRIMARY KEY,order_id uuid,revision_id uuid,entry_type text,refund_of uuid,amount numeric,currency char(3),payment_method text,external_reference text);
 CREATE TABLE wholesale_financial_account_mappings(payment_method text,account_id text);
 CREATE TABLE wholesale_financial_postings(payment_entry_id uuid,status text,account_id text);
 CREATE FUNCTION financial_ready_period() RETURNS uuid LANGUAGE sql AS $$ SELECT '${r}'::uuid $$;
 CREATE FUNCTION assert_wholesale_admin_actor(actor uuid) RETURNS void LANGUAGE plpgsql AS $$ BEGIN IF actor IS DISTINCT FROM '${c}'::uuid THEN RAISE EXCEPTION 'ADMIN_REQUIRED'; END IF; END $$;
 INSERT INTO customers(id)VALUES('${c}'),('${other}');
 INSERT INTO wholesale_orders VALUES('${o}','${c}','confirmed','${r}');
 INSERT INTO wholesale_order_revisions VALUES('${r}','${o}',100,'ARS');
 INSERT INTO wholesale_financial_account_mappings VALUES('mercadopago','mercadopago');`);
 await db.exec(fs.readFileSync('scripts/maintenance/proposed-wholesale-checkout.sql','utf8'));
 await db.exec(fs.readFileSync('scripts/maintenance/proposed-wholesale-transfer-notices.sql','utf8'));
 const save=(customer=c,amount=40,key=n)=>db.query('SELECT record_wholesale_transfer_notice($1,$2,$3,$4,$5,NULL) AS notice',[customer,o,amount,key,'inform']);
 assert.equal((await save()).rows[0].notice.status,'pending');
 assert.equal((await save()).rows[0].notice.id,n);
 await assert.rejects(save(other),/NOTICE_OWNER/);
 await assert.rejects(save(c,41),/NOTICE_KEY_REUSED/);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM wholesale_transfer_notices')).rows[0].n,1);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM wholesale_payment_entries')).rows[0].n,0);
 assert.equal((await db.query('SELECT count(*)::int AS n FROM wholesale_financial_postings')).rows[0].n,0);
 await assert.rejects(db.query("SELECT resolve_wholesale_transfer_notice($1,$2,'verified',$3,$4)",[o,n,i,c]),/NOTICE_PAYMENT_PROOF/);
 await assert.rejects(db.query("SELECT resolve_wholesale_transfer_notice($1,$2,'not_received',NULL,$3)",[o,n,other]),/ADMIN_REQUIRED/);
 await assert.rejects(db.query('SELECT begin_wholesale_checkout($1,$2,70,$3)',[c,o,i]),/NOTICE_AMOUNT_RESERVED/);
 await db.query('SELECT begin_wholesale_checkout($1,$2,60,$3)',[c,o,i]);
 await db.query('SELECT record_wholesale_transfer_notice($1,$2,NULL,$3,$4,$3)',[c,o,n,'withdraw']);
 assert.equal((await db.query('SELECT status FROM wholesale_transfer_notices WHERE id=$1',[n])).rows[0].status,'withdrawn');
 await assert.rejects(db.query('SELECT record_wholesale_transfer_notice($1,$2,50,gen_random_uuid(),$3,NULL)',[c,o,'inform']),/NOTICE_AMOUNT_RESERVED/);
 await db.query('SELECT record_wholesale_transfer_notice($1,$2,40,gen_random_uuid(),$3,NULL)',[c,o,'inform']);
 await assert.rejects(db.query('SELECT close_verified_wholesale_checkout($1,$2,$3,NULL,false)',[c,o,i]),/CHECKOUT_NOT_SAFE_TO_CLOSE/);
 await db.query("UPDATE wholesale_checkout_intents SET expires_at=clock_timestamp()-interval '1 second' WHERE id=$1",[i]);
 await db.query('SELECT close_verified_wholesale_checkout($1,$2,$3,NULL,true)',[c,o,i]);
 assert.equal((await db.query('SELECT state FROM wholesale_checkout_intents WHERE id=$1',[i])).rows[0].state,'closed');
 await db.query('SELECT begin_wholesale_checkout($1,$2,60,gen_random_uuid())',[c,o]);
 const latestNotice=(await db.query("SELECT id FROM wholesale_transfer_notices WHERE status='pending'")).rows[0].id;
 await db.query("SELECT resolve_wholesale_transfer_notice($1,$2,'not_received',NULL,$3)",[o,latestNotice,c]);
 await db.query("SELECT resolve_wholesale_transfer_notice($1,$2,'not_received',NULL,$3)",[o,latestNotice,c]);
 assert.equal((await db.query("SELECT count(*)::int AS n FROM wholesale_transfer_notice_events WHERE event='not_received'")).rows[0].n,1);
 await db.exec('SET ROLE anon');
 await assert.rejects(save(),/permission denied/);
 }finally{await db.close();}
});
